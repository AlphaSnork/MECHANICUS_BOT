def h1(t): doc.add_heading(t, level=1)
def h2(t): doc.add_heading(t, level=2)
def h3(t): doc.add_heading(t, level=3)

def p(t, bold=False, italic=False, color=None, size=None, align=None, space_after=6):
    par = doc.add_paragraph()
    r = par.add_run(t)
    r.bold = bold; r.italic = italic
    if color: r.font.color.rgb = color
    if size: r.font.size = Pt(size)
    if align: par.alignment = align
    par.paragraph_format.space_after = Pt(space_after)
    return par

def bullet(t, level=0):
    par = doc.add_paragraph(style="List Bullet" if level == 0 else "List Bullet 2")
    par.add_run(t)
    par.paragraph_format.space_after = Pt(2)
    return par

def note(t):
    par = doc.add_paragraph()
    r = par.add_run(t)
    r.italic = True; r.font.size = Pt(9); r.font.color.rgb = GREY
    par.paragraph_format.space_after = Pt(8)
    return par

def img(fn, width=6.3, cap=None):
    par = doc.add_paragraph()
    par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    par.add_run().add_picture(A + fn, width=Inches(width))
    par.paragraph_format.space_after = Pt(2)
    if cap:
        c = doc.add_paragraph()
        c.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = c.add_run(cap)
        r.italic = True; r.font.size = Pt(8.5); r.font.color.rgb = GREY
        c.paragraph_format.space_after = Pt(10)

def table(headers, rows, widths=None, font=8.5):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i, htxt in enumerate(headers):
        hdr[i].text = ""
        r = hdr[i].paragraphs[0].add_run(htxt)
        r.bold = True; r.font.size = Pt(font)
        sh = OxmlElement("w:shd"); sh.set(qn("w:fill"), "2B2D31"); sh.set(qn("w:val"), "clear")
        hdr[i]._tc.get_or_add_tcPr().append(sh)
        r.font.color.rgb = RGBColor(0xF2, 0xF3, 0xF5)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ""
            r = cells[i].paragraphs[0].add_run(str(val))
            r.font.size = Pt(font)
    if widths:
        for i, w in enumerate(widths):
            for row in t.rows:
                row.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t

def script(lines):
    """проигрывка: список (кто, текст)."""
    for who, txt in lines:
        par = doc.add_paragraph()
        par.paragraph_format.left_indent = Cm(0.6)
        par.paragraph_format.space_after = Pt(3)
        r = par.add_run(who + ": ")
        r.bold = True
        r.font.color.rgb = CRIM if who in ("Игрок", "Бот") else GOLD
        r.font.size = Pt(9.5)
        r2 = par.add_run(txt)
        r2.font.size = Pt(9.5)

